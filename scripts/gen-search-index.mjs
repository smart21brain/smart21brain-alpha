// Builds js/search-index.js — the site-wide search index used by js/search.js and search.html.
// Run after adding/changing pages, games, videos, books or courses:  node scripts/gen-search-index.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const decode = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
  .replace(/&#39;|&apos;/g, "'").replace(/&nbsp;/g, ' ').replace(/&mdash;/g, '—').replace(/&middot;/g, '·');
const strip = (s) => decode(s.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();

// ---- Swahili translations (key -> sw text) from i18n.js: the last occurrence of a key is the Kiswahili one
const i18n = read('js/i18n.js');
const seen = {};
for (const m of i18n.matchAll(/\b([a-z][a-z0-9_]*):\s*'((?:[^'\\]|\\.)*)'/g)) (seen[m[1]] ||= []).push(m[2].replace(/\\'/g, "'"));
const sw = (key) => (key && seen[key] && seen[key].length > 1 ? seen[key][seen[key].length - 1] : '');

const out = [];
const add = (title, type, href, kw = '') => {
  title = title.replace(/\s+/g, ' ').trim();
  if (!title || title.length > 140) return;
  out.push([title, type, href, kw.replace(/\s+/g, ' ').trim()]);
};

// ---- pages
const SKIP = /^(admin|login|register|forgot-password|reset-password|google|splash|welcome|onboarding|school-login|school-verify|shop-login|shop-verify|institution-login|institution-start|institution-app|school-app|shop-app|stationery-app|blog-post|certificate|final-exam|module-quiz|course-complete|lesson|game|video|book|quiz|course|dashboard|profile)\b/;
const PAGE_TYPE = { 'games.html': 'Games', 'videos.html': 'Videos', 'library.html': 'Books', 'courses.html': 'Courses' };
const html = fs.readdirSync(root).filter((f) => f.endsWith('.html'));
const CARD_SOURCES = { 'games.html': 'Game', 'videos.html': 'Video', 'library.html': 'Book', 'kids.html': 'Kids', 'cartoons.html': 'Cartoon',
  'subjects.html': 'Subject', 'gallery.html': 'Gallery', 'blog.html': 'Blog' };

for (const f of html) {
  const base = f.replace('.html', '');
  const src = read(f);
  const title = decode((src.match(/<title>([\s\S]*?)<\/title>/i) || [])[1] || '').replace(/\s*[|—-]\s*Smart21Brain.*$/i, '').trim();
  const desc = decode((src.match(/<meta name="description" content="([^"]*)"/i) || [])[1] || '');

  if (/^game-/.test(f)) {
    add(title.replace(/\s*[—-]\s*Educational Game.*$/i, ''), 'Game', f, desc);
  } else if (!SKIP.test(base)) {
    const heads = [...src.matchAll(/<h[12][^>]*>([\s\S]*?)<\/h[12]>/gi)].map((m) => strip(m[1])).filter(Boolean).slice(0, 6).join(' ');
    add((title || base).split(/\s+[—|]\s+/)[0], PAGE_TYPE[f] ? 'Section' : 'Page', f, `${title} ${desc} ${heads}`);
  }

  // cards on hub pages: <a href=X> ... <h3 data-i18n=k>Title</h3> ...  or <h3><a href=X data-i18n=k>Title</a></h3>
  const type = CARD_SOURCES[f];
  if (type) {
    const seenTitles = new Set();
    const push = (href, key, text) => {
      const t = strip(text);
      if (!t || t.length < 3 || /^\$\{/.test(t) || seenTitles.has(t)) return;
      seenTitles.add(t);
      if (/^(#|javascript|http)/.test(href)) href = f;
      add(t, type, href || f, sw(key));
    };
    const tag = f === 'subjects.html' ? 'h2' : 'h3';
    const re = new RegExp(`<${tag}([^>]*)>([\\s\\S]*?)<\\/${tag}>`, 'gi');
    for (const m of src.matchAll(re)) {
      const inner = m[2];
      const key = (/data-i18n="([^"]+)"/.exec(m[1]) || /data-i18n="([^"]+)"/.exec(inner) || [])[1];
      let href = (/<a\s+[^>]*href="([^"]+)"/.exec(inner) || [])[1];
      if (!href) {
        const before = src.slice(Math.max(0, m.index - 700), m.index);
        const anchors = [...before.matchAll(/<a\s+[^>]*href="([^"]+)"/g)];
        href = anchors.length ? anchors[anchors.length - 1][1] : f;
      }
      push(href, key, inner);
    }
  }
}

// ---- courses + lessons from the built-in catalog
const sandbox = { window: {}, console };
vm.createContext(sandbox);
vm.runInContext(read('js/courses-data.js'), sandbox);
for (const c of sandbox.window.S21Courses.all) {
  const href = `course.html?slug=${encodeURIComponent(c.slug)}`;
  add(c.title, 'Course', href, `${c.description || ''} ${c.category_name || ''} ${c.level || ''} ${c.instructor_name || ''}`);
  for (const l of c.lessons || []) add(l.title, 'Lesson', `lesson.html?id=${encodeURIComponent(l.id)}`, `${c.title} ${l.module || ''}`);
}

// ---- de-duplicate (same title+type) and write
const uniq = new Map();
for (const e of out) { const k = `${e[1]}|${e[0].toLowerCase()}`; if (!uniq.has(k)) uniq.set(k, e); }
const list = [...uniq.values()];
fs.writeFileSync(path.join(root, 'js/search-index.js'),
  `// GENERATED by scripts/gen-search-index.mjs — do not edit by hand. ${list.length} entries.\n` +
  `window.S21_SEARCH_INDEX = ${JSON.stringify(list)};\n`);
const counts = {};
list.forEach((e) => { counts[e[1]] = (counts[e[1]] || 0) + 1; });
console.log(`search-index.js: ${list.length} entries`, counts);
