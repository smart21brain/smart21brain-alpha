// Regenerates src/lib/catalog-index.js from js/courses-data.js.
//
// The built-in course catalog lives in the browser (js/courses-data.js). The
// server needs a tiny copy of its SHAPE — which courses exist, their subject
// and their lesson ids — so it can (a) accept only real lessons when syncing a
// learner's progress, (b) tell when a course is fully completed and (c) award
// subject badges. No lesson text is copied.
//
// Run again whenever you add or remove a built-in course or lesson:
//   node scripts/gen-catalog-index.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const win = {};
vm.runInNewContext(readFileSync(join(root, 'js/courses-data.js'), 'utf8'), { window: win, console });
const courses = win.S21Courses && win.S21Courses.all;
if (!Array.isArray(courses) || !courses.length) throw new Error('Could not read the course catalog.');

const index = {};
for (const c of courses) {
  index[c.slug] = { title: c.title, category: c.category_slug, lessons: (c.lessons || []).map((l) => String(l.id)) };
}
const out = `// GENERATED by scripts/gen-catalog-index.mjs from js/courses-data.js — do not edit by hand.
// ${courses.length} courses. Re-run the script after changing the built-in catalog.
export const CATALOG = ${JSON.stringify(index, null, 2)};
`;
writeFileSync(join(root, 'src/lib/catalog-index.js'), out);
console.log(`Wrote src/lib/catalog-index.js (${courses.length} courses, ${Object.values(index).reduce((n, c) => n + c.lessons.length, 0)} lessons)`);
